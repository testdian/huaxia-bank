def shade_row(row, hex_color='D9E1F2'):
    for cell in row.cells:
        tc = cell._tc
        tcPr = tc.get_or_add_tcPr()
        shd = OxmlElement('w:shd')
        shd.set(qn('w:val'), 'clear')
        shd.set(qn('w:color'), 'auto')
        shd.set(qn('w:fill'), hex_color)
        tcPr.append(shd)

def add_table(headers, rows, col_widths=None, header_color='1F4E79', header_text_color=(255,255,255)):
    n_cols = len(headers)
    table = doc.add_table(rows=1 + len(rows), cols=n_cols)
    table.style = 'Table Grid'
    # 列宽
    if col_widths:
        for i, w in enumerate(col_widths):
            for cell in table.columns[i].cells:
                cell.width = Cm(w)
    # 表头
    hdr = table.rows[0]
    shade_row(hdr, header_color)
    for i, h in enumerate(headers):
        cell = hdr.cells[i]
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(h)
        set_font(run, size_pt=9, bold=True, color=header_text_color, name='黑体')
    # 内容行
    for ri, row_data in enumerate(rows):
        row_obj = table.rows[ri + 1]
        # 交替底色
        if ri % 2 == 0:
            shade_row(row_obj, 'EEF3FB')
        for ci, cell_text in enumerate(row_data):
            cell = row_obj.cells[ci]
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            p = cell.paragraphs[0]
            run = p.add_run(str(cell_text))
            set_font(run, size_pt=9)
    return table

