# ─── helpers ──────────────────────────────────────────────────────────────────

def _run(p, text, bold=False, size=None, color=None, highlight=None):
    r = p.add_run(text)
    r.font.name = "宋体"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    if size:
        r.font.size = Pt(size)
    if bold:
        r.bold = True
    if color:
        r.font.color.rgb = color
    if highlight:
        r.font.highlight_color = highlight
    return r


def hp(doc, text, level):
    """标题段落"""
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        r.font.name = "黑体"
        r._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")
    return p


def np(doc, text="", style="Normal"):
    """普通正文段落"""
    p = doc.add_paragraph(style=style)
    if text:
        _run(p, text, size=10.5)
    return p


def fp(doc, text):
    """功能点描述段落 (Normal Indent)"""
    p = doc.add_paragraph(style="Normal Indent")
    if text:
        _run(p, text, size=10.5)
    return p


def lp(doc, text):
    """列表项（List Paragraph）"""
    p = doc.add_paragraph(style="List Paragraph")
    if text:
        _run(p, text, size=10.5)
    return p


def set_cell_bg(cell, fill="D9EAF7"):
    tcp = cell._tc.get_or_add_tcPr()
    shd = tcp.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tcp.append(shd)
    shd.set(qn("w:fill"), fill)


def add_field_table(doc, rows, title_cols=None):
    """
    输入项/输出项字段表
    标准列：字段名 | 类型 | 是否必输 | 长度 | 默认值 | 输入限制 | 说明
    rows: list of (字段名, 类型, 是否必输, 长度, 默认值, 输入限制, 说明)
    """
    if title_cols is None:
        title_cols = ["字段名", "类型", "是否必输", "长度", "默认值", "输入限制（或数据字典）", "说明"]
    t = doc.add_table(rows=1, cols=len(title_cols))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.style = "Table Grid"
    hdr = t.rows[0].cells
    for i, h in enumerate(title_cols):
        hdr[i].text = h
        set_cell_bg(hdr[i], "D9EAF7")
        for p in hdr[i].paragraphs:
            for r in p.runs:
                r.bold = True
                r.font.name = "宋体"
                r._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
                r.font.size = Pt(9)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = "" if v is None else str(v)
            cells[i].vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            for p in cells[i].paragraphs:
                for r in p.runs:
                    r.font.name = "宋体"
                    r._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
                    r.font.size = Pt(9)
    return t


