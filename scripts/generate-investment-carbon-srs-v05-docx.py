def pending(doc, text):
    """待确认项（黄色高亮）"""
    p = doc.add_paragraph(style="Normal")
    r = _run(p, "【待确认】" + text, highlight=WD_COLOR_INDEX.YELLOW)
    return p


def feat(doc, no, name, desc, input_rows, flow_lines, check_lines,
         output_text, ui_text, rule_lines, data_text,
         output_rows=None):
    """
    按模版格式写一个功能点：段落体裁
    input_rows: list of (字段名, 类型, 是否必输, 长度) tuples, can be None
    output_rows: list of (字段名, 类型, 数据种类, 长度/精度) tuples, can be None
    flow_lines: list of str (处理流程步骤)
    check_lines: list of str (校验规则，可为空)
    rule_lines: list of str (业务规则)
    """
    hp(doc, name, 4)
    fp(doc, f"功能编号：{no}")
    fp(doc, f"功能名称：{name}")
    fp(doc, f"功能描述：{desc}")
    fp(doc, "输入项：")
    if input_rows:
        add_field_table(doc, input_rows)
    fp(doc, "处理流程：")
    if check_lines:
        fp(doc, "校验：")
        for c in check_lines:
            lp(doc, c)
    fp(doc, "处理流程：")
    for fl in flow_lines:
        lp(doc, fl)
    fp(doc, f"输出项：{output_text}")
    if output_rows:
        add_field_table(doc, output_rows,
                        title_cols=["字段名", "类型", "数据种类", "长度/精度"])
    fp(doc, f"界面设计：{ui_text}")
    fp(doc, "凭证报表：不涉及。")
    fp(doc, "会计分录：不涉及。")
    fp(doc, "业务规则：")
    for r in rule_lines:
        lp(doc, r)
    fp(doc, f"数据规则：{data_text}")


