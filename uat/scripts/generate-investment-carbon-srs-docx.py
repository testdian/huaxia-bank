def add_pending(doc: Document, label: str, text: str, red=False):
    p = doc.add_paragraph()
    r1 = p.add_run(label)
    r1.bold = True
    r1.font.name = "宋体"
    r1._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    r1.font.highlight_color = WD_COLOR_INDEX.YELLOW
    r2 = p.add_run(text)
    r2.font.name = "宋体"
    r2._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    r2.font.highlight_color = WD_COLOR_INDEX.YELLOW
    if red:
        r2.font.color.rgb = RGBColor(192, 0, 0)
    return p


