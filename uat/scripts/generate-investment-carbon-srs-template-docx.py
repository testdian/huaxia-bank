def set_font(run, name="宋体", size=10.5, bold=False, color=None, highlight=None):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    if highlight:
        run.font.highlight_color = highlight


def set_shading(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def para(doc, text="", style="Normal", bold_prefix=None):
    if style not in doc.styles:
        style = "Normal"
    p = doc.add_paragraph(style=style)
    if bold_prefix and text.startswith(bold_prefix):
        r1 = p.add_run(bold_prefix)
        set_font(r1, bold=True)
        r2 = p.add_run(text[len(bold_prefix):])
        set_font(r2)
    else:
        r = p.add_run(text)
        set_font(r)
    return p


def heading(doc, text, level):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        set_font(r, "黑体", 14 if level == 1 else 12, bold=True)
    return p


def table(doc, headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = h
        c.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        set_shading(c, "D9EAF7")
        for p in c.paragraphs:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for r in p.runs:
                set_font(r, bold=True)
    for row in rows:
        cells = t.add_row().cells
        normalized = list(row)[:len(headers)] + [""] * max(0, len(headers) - len(row))
        for i, v in enumerate(normalized):
            cells[i].text = "" if v is None else str(v)
            cells[i].vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            for p in cells[i].paragraphs:
                for r in p.runs:
                    set_font(r)
    return t


def note_pending(doc, text):
    p = doc.add_paragraph()
    r1 = p.add_run("待确认：")
    set_font(r1, bold=True, highlight=WD_COLOR_INDEX.YELLOW)
    r2 = p.add_run(text)
    set_font(r2, highlight=WD_COLOR_INDEX.YELLOW)


def note_red(doc, text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_font(r, bold=True, color=(192, 0, 0))


def bullet(doc, items):
    for item in items:
        p = doc.add_paragraph(style="List Paragraph")
        r = p.add_run(item)
        set_font(r)


